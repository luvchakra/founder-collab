import { launch, SP } from "./.browser.mjs";
import { readFileSync } from "node:fs";
const BASE = "https://ark.wonderapps.biz";
const email = readFileSync(`${SP}/rbac-e2e-email`, "utf8").trim();
const password = readFileSync(`${SP}/rbac-e2e-password`, "utf8").trim();
const token = readFileSync(`${SP}/rbac-invite-token`, "utf8").trim();
const b = await launch(); const ctx = await b.newContext(); const page = await ctx.newPage();
const log = (k, v) => console.log(k.padEnd(44), v);
await page.goto(`${BASE}/invite/${token}`);
log("signed-out invite page heading", await page.getByRole("heading", { level: 1 }).innerText());
log("business name hidden while signed out", !(await page.getByText("Acme Home Security").count()));
await page.getByRole("link", { name: "Sign in to accept" }).click();
await page.waitForURL(/\/login/);
log("cookie is httpOnly", (await ctx.cookies()).find((c) => c.name === "wa_pending_invite")?.httpOnly === true);
await page.getByLabel("Email").fill(email);
await page.locator('input[name="password"]').fill(password);
await page.getByRole("button", { name: "Log In" }).click();
await page.waitForURL((u) => u.pathname.startsWith("/invite/"), { timeout: 30000 });
log("after login, sent back to invitation", new URL(page.url()).pathname.startsWith("/invite/"));
log("invitation heading", await page.getByRole("heading", { level: 1 }).innerText());
log("role shown", await page.locator("dl").innerText().then((t) => t.replace(/\s+/g, " ")));
await page.getByRole("button", { name: "Accept invitation" }).click();
await page.waitForURL((u) => !u.pathname.startsWith("/invite/"), { timeout: 30000 });
const slug = new URL(page.url()).pathname.split("/")[1];
log("landed on", new URL(page.url()).pathname);
log("pending cookie cleared", !(await ctx.cookies()).find((c) => c.name === "wa_pending_invite"));
await page.getByRole("button", { name: /Acme Home Security/ }).first().click().catch(() => {});
log("switcher shows Viewer", (await page.getByRole("menu").getByText("Viewer").count()) > 0);
await page.keyboard.press("Escape");
await page.goto(`${BASE}/${slug}/admin/users`);
log("Users & Access for a viewer", (await page.getByText("You don't have permission").count()) > 0 ? "no-permission message" : "VISIBLE (unexpected)");
await page.goto(`${BASE}/${slug}/billing`);
log("billing: can't change plan", (await page.getByRole("link", { name: /Change plan|Upgrade plan/ }).count()) === 0);
const res = await page.request.post(`${BASE}/api/billing/checkout`, { data: { businessSlug: slug, planId: "40246aaa-d671-47d5-a530-e7978a9da924", billingInterval: "month", idempotencyKey: "00000000-0000-4000-8000-00000000abcd" } });
log("checkout API for a viewer", res.status());
await page.goto(`${BASE}/${slug}/discovery/dashboard`);
log("discovery (viewer has discovery.view)", (await page.getByText("You don't have access").count()) === 0 ? "opens" : "blocked");
await page.goto(`${BASE}/dashboard`);
log("dashboard lists invited business", (await page.getByText("Acme Home Security").count()) > 0);
await b.close();
