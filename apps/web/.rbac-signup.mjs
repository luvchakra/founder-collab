import { launch, SP } from "./.browser.mjs";
import { readFileSync } from "node:fs";
const BASE = "https://ark.wonderapps.biz";
const email = readFileSync(`${SP}/rbac-e2e-email`, "utf8").trim();
const password = readFileSync(`${SP}/rbac-e2e-password`, "utf8").trim();
const b = await launch(); const page = await b.newPage();
await page.goto(`${BASE}/signup`);
await page.locator("#name").fill("RBAC Viewer (E2E)");
await page.locator("#email").fill(email);
await page.locator('input[name="password"]').fill(password);
await page.locator('button[type="submit"]').first().click();
await page.waitForTimeout(5000);
console.log("after signup:", new URL(page.url()).pathname);
await b.close();
